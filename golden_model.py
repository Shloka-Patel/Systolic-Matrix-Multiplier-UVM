#!/usr/bin/env python3
"""
golden_model.py -- NumPy golden reference + test-vector generator for the matrix multiplier.

Usage:   python3 golden_model.py <N> [seed]        e.g.  python3 golden_model.py 4

Writes (in the current directory):
    vectors.svh  -- SystemVerilog include file read by the UVM sequence
    vectors.txt  -- plain text copy (one test per line: A row-major, B row-major, C row-major)
Prints a prediction of which functional-coverage bins these vectors will hit.

Hardware is UNSIGNED, W = 8 bit inputs, accumulator width 2W + log2(N) -> results are exact.
"""
import sys
import math
import random
import numpy as np

W = 8
MAXV = (1 << W) - 1          # 255

# ---------------------------------------------------------------- golden model
def golden(A, B):
    """Ground truth. int64 so nothing can overflow."""
    return np.matmul(np.array(A, dtype=np.int64), np.array(B, dtype=np.int64))

# ---------------------------------------------------------------- matrix kinds
K_ZERO, K_IDENT, K_ALLMAX, K_SPARSE, K_DENSE = range(5)
KIND_NAMES = ["ZERO", "IDENT", "ALLMAX", "SPARSE", "DENSE"]

def classify(m):
    """Must match classify() in the SystemVerilog coverage class."""
    n = len(m)
    flat = [v for row in m for v in row]
    if all(v == 0 for v in flat):
        return K_ZERO
    if all(m[i][j] == (1 if i == j else 0) for i in range(n) for j in range(n)):
        return K_IDENT
    if all(v == MAXV for v in flat):
        return K_ALLMAX
    if any(v == 0 for v in flat):
        return K_SPARSE
    return K_DENSE

def max_bin(mx):
    """Bins of cp_a_max / cp_b_max in the SystemVerilog coverage class."""
    if mx == 0:        return "zero"
    if mx <= 15:       return "low"
    if mx <= 239:      return "mid"
    if mx <= 254:      return "big"
    return "full"

# ---------------------------------------------------------------- generators
def ident(n):  return [[1 if i == j else 0 for j in range(n)] for i in range(n)]
def zeros(n):  return [[0] * n for _ in range(n)]
def full(n):   return [[MAXV] * n for _ in range(n)]

def rnd(n, lo, hi):
    return [[random.randint(lo, hi) for _ in range(n)] for _ in range(n)]

def canonical(kind, n):
    """One representative matrix of each kind."""
    if kind == K_ZERO:   return zeros(n)
    if kind == K_IDENT:  return ident(n)
    if kind == K_ALLMAX: return full(n)
    if kind == K_SPARSE:
        while True:
            m = [[0 if random.random() < 0.5 else random.randint(1, 254) for _ in range(n)] for _ in range(n)]
            if classify(m) == K_SPARSE:
                return m
    while True:                       # K_DENSE
        m = rnd(n, 1, 254)
        if classify(m) == K_DENSE:
            return m

def force_one(m, value):
    n = len(m)
    m[random.randrange(n)][random.randrange(n)] = value
    return m

def random_matrix(mode, n):
    if mode == "full":   return rnd(n, 0, 254)
    if mode == "small":  return rnd(n, 0, 15)
    if mode == "mid":    return rnd(n, 0, 200)
    if mode == "big":    return force_one(rnd(n, 0, 200), random.randint(240, 254))
    if mode == "has255": return force_one(rnd(n, 0, 254), MAXV)
    if mode == "sparse": return [[0 if random.random() < 0.6 else random.randint(1, 255) for _ in range(n)] for _ in range(n)]
    if mode == "dense":  return rnd(n, 1, 254)
    raise ValueError(mode)

RANDOM_MODES = ["full", "small", "mid", "big", "has255", "sparse", "dense"]
RANDOM_PER_MODE = 20

def make_vectors(n):
    vecs = []
    # 1) directed: every kind x kind combination (25 vectors)
    for ka in range(5):
        for kb in range(5):
            vecs.append((canonical(ka, n), canonical(kb, n)))
    # 2) directed: the classic cases
    vecs.append((ident(n), rnd(n, 0, 254)))      # I x B = B
    vecs.append((rnd(n, 0, 254), ident(n)))      # A x I = A
    vecs.append((full(n), full(n)))              # worst-case value of every output
    # 3) constrained-random, every mode paired with every other mode
    for ma in RANDOM_MODES:
        for _ in range(RANDOM_PER_MODE):
            mb = random.choice(RANDOM_MODES)
            vecs.append((random_matrix(ma, n), random_matrix(mb, n)))
    return vecs

# ---------------------------------------------------------------- writers
def flat(m):
    return [v for row in m for v in row]

def write_files(n, vecs):
    rows = []
    for A, B in vecs:
        C = golden(A, B)
        rows.append(flat(A) + flat(B) + [int(x) for x in C.flatten()])

    with open("vectors.txt", "w") as f:
        for r in rows:
            f.write(" ".join(str(x) for x in r) + "\n")

    with open("vectors.svh", "w") as f:
        f.write(f"// Auto-generated by golden_model.py  (N={n}, {len(rows)} vectors) -- do not edit\n")
        f.write(f"localparam int VEC_N       = {n};\n")
        f.write(f"localparam int NUM_VECTORS = {len(rows)};\n")
        f.write(f"int vec_data [NUM_VECTORS][{3*n*n}] = '{{\n")
        for i, r in enumerate(rows):
            comma = "," if i < len(rows) - 1 else ""
            f.write("  '{" + ",".join(str(x) for x in r) + "}" + comma + "\n")
        f.write("};\n")
    return rows

# ---------------------------------------------------------------- coverage predictor
def predict_coverage(vecs):
    hit = set()
    for A, B in vecs:
        C = golden(A, B)
        ka, kb = classify(A), classify(B)
        hit.add(("a_kind", ka))
        hit.add(("b_kind", kb))
        hit.add(("cross", ka, kb))
        hit.add(("a_max", max_bin(max(flat(A)))))
        hit.add(("b_max", max_bin(max(flat(B)))))
        hit.add(("c_zero", int(not C.any())))
    universe = ([("a_kind", k) for k in range(5)] + [("b_kind", k) for k in range(5)] +
                [("cross", a, b) for a in range(5) for b in range(5)] +
                [("a_max", b) for b in ["zero", "low", "mid", "big", "full"]] +
                [("b_max", b) for b in ["zero", "low", "mid", "big", "full"]] +
                [("c_zero", 0), ("c_zero", 1)])
    missing = [u for u in universe if u not in hit]
    return len(universe) - len(missing), len(universe), missing

# ---------------------------------------------------------------- main
if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    n = int(sys.argv[1])
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 2026
    random.seed(seed)

    vecs = make_vectors(n)
    write_files(n, vecs)

    # self-check against an independent triple-loop (proves np.matmul usage is right)
    for A, B in vecs:
        C = golden(A, B)
        for i in range(n):
            for j in range(n):
                assert C[i][j] == sum(A[i][k] * B[k][j] for k in range(n))
        assert C.max() < (1 << (2 * W + int(math.ceil(math.log2(n)))))   # fits accumulator

    hit, total, missing = predict_coverage(vecs)
    print(f"N={n}: wrote {len(vecs)} test vectors to vectors.svh and vectors.txt")
    print(f"Predicted functional coverage of these vectors: {hit}/{total} bins = {100.0*hit/total:.1f}%")
    for m in missing:
        print("   not hit:", m)
