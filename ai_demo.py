#!/usr/bin/env python3
"""
ai_demo.py -- builds the neural-network-layer demo for the FPGA.

One fully connected layer, 4 inputs -> 4 outputs (a 4-class classifier):
        scores = W x X          W : 4x4 weights (row c = prototype of class c)
                                X : 4x4, each COLUMN is one input sample (4 samples at once)
        class  = argmax over the scores of a column

The hardware multiplier is UNSIGNED, so weights/inputs are non-negative integers
(a trained layer would be quantised to 8-bit and offset/scaled the same way).

Writes ai_demo_data.svh (used by the FPGA top and its testbench) and prints the
expected result table -- these are the numbers you must see on the board LEDs.
"""
import numpy as np

# Class prototypes (rows).  Values 0..90.
W = np.array([[90, 20, 10, 10],
              [10, 90, 20, 10],
              [10, 10, 90, 20],
              [20, 10, 10, 90]], dtype=np.int64)

# Four input samples, one per COLUMN of X.  Each sample is a noisy version of one class.
samples = np.array([[60, 15,  5, 10],      # sample 0 -> should be class 0
                    [10, 55, 20,  5],      # sample 1 -> should be class 1
                    [ 5, 20, 65, 10],      # sample 2 -> should be class 2
                    [15,  5, 10, 50]],     # sample 3 -> should be class 3
                   dtype=np.int64)
X = samples.T.copy()                       # column j = sample j

S = W @ X                                  # S[c][j] = score of class c for sample j
pred = S.argmax(axis=0)
intended = np.arange(4)

assert (pred == intended).all(), f"demo data does not classify as designed: {pred}"
assert S.max() < (1 << 15), "scores must fit in 15 LED bits"
assert W.max() < 256 and X.max() < 256

print("Weight matrix W (rows = classes):")
print(W)
print("\nInput matrix X (columns = samples):")
print(X)
print("\nExpected score matrix S = W x X   (S[class][sample])  <-- values on the LEDs")
print(S)
print("\nPredicted class per sample:", pred.tolist(), "  (intended:", intended.tolist(), ")")

def sv_mat(name, M, typ):
    rows = ",\n    ".join("'{" + ",".join(str(int(v)) for v in r) + "}" for r in M)
    return f"localparam {typ} {name} [0:3][0:3] = '{{\n    {rows}\n}};\n"

with open("ai_demo_data.svh", "w") as f:
    f.write("// Auto-generated by ai_demo.py -- do not edit\n")
    f.write(sv_mat("WMAT", W, "int unsigned"))
    f.write(sv_mat("XMAT", X, "int unsigned"))
    f.write(sv_mat("EXPSCORE", S, "int unsigned"))
    f.write("localparam int unsigned EXPCLASS [0:3] = '{" + ",".join(str(int(p)) for p in pred) + "};\n")
print("\nwrote ai_demo_data.svh")
