// matrix_pkg.sv -- complete UVM environment for the parameterized matrix multiplier
//
//   Matrix size is chosen at compile time:   +define+N_SIZE=4      (default 4)
//   vectors.svh (made by golden_model.py <N>) MUST be for the same N -- checked at run time.
//
//   Tests:  matrix_test       -> Python golden-model vectors only      (stimulus + expected from NumPy)
//           matrix_rand_test  -> SystemVerilog constrained-random only (expected from an SV reference)
//           matrix_full_test  -> both, one after the other             (use this one)
//
// NOTE: no timescale directives anywhere (matches the files that already ran on your NCSim).
`ifndef N_SIZE
  `define N_SIZE 4
`endif

package matrix_pkg;
    import uvm_pkg::*;
    `include "uvm_macros.svh"

    localparam int N    = `N_SIZE;
    localparam int W    = 8;
    localparam int CW   = 2*W + $clog2(N);
    localparam int MAXV = (1 << W) - 1;

    typedef logic [W-1:0]  mat_t  [0:N-1][0:N-1];
    typedef logic [CW-1:0] cmat_t [0:N-1][0:N-1];
    typedef virtual matrix_if #(.N(N), .W(W)) vif_t;

    typedef enum int {K_ZERO = 0, K_IDENT = 1, K_ALLMAX = 2, K_SPARSE = 3, K_DENSE = 4} mat_kind_e;

    // ======================================================================
    // 1. Transaction
    // ======================================================================
    class matrix_item extends uvm_sequence_item;
        `uvm_object_utils(matrix_item)

        rand mat_t        a;
        rand mat_t        b;
        rand int unsigned mode_a;       // 0 full-range, 1 small values, 2 sparse, 3 large values
        rand int unsigned mode_b;
        cmat_t            exp_c;        // expected result  (Python golden model OR SV reference)
        cmat_t            act_c;        // result seen on the DUT by the monitor

        constraint c_modes {
            mode_a dist {0 := 3, 1 := 2, 2 := 3, 3 := 2};
            mode_b dist {0 := 3, 1 := 2, 2 := 3, 3 := 2};
        }
        constraint c_a_vals {
            foreach (a[i,j]) {
                if (mode_a == 1)      a[i][j] inside {[0:15]};
                else if (mode_a == 2) a[i][j] dist {0 := 6, [1:255] :/ 4};
                else if (mode_a == 3) a[i][j] inside {[128:255]};
                else                  a[i][j] inside {[0:255]};
            }
        }
        constraint c_b_vals {
            foreach (b[i,j]) {
                if (mode_b == 1)      b[i][j] inside {[0:15]};
                else if (mode_b == 2) b[i][j] dist {0 := 6, [1:255] :/ 4};
                else if (mode_b == 3) b[i][j] inside {[128:255]};
                else                  b[i][j] inside {[0:255]};
            }
        }

        function new(string name = "matrix_item");
            super.new(name);
        endfunction

        // SystemVerilog reference model (used for the constrained-random sequence)
        function void compute_expected();
            for (int i = 0; i < N; i++) begin
                for (int j = 0; j < N; j++) begin
                    longint unsigned s;
                    s = 0;
                    for (int k = 0; k < N; k++)
                        s += longint'(a[i][k]) * longint'(b[k][j]);
                    exp_c[i][j] = s[CW-1:0];
                end
            end
        endfunction

        function void post_randomize();
            compute_expected();
        endfunction

        function string convert2string();
            return $sformatf("A[0][0]=%0d B[0][0]=%0d exp_C[0][0]=%0d act_C[0][0]=%0d",
                             a[0][0], b[0][0], exp_c[0][0], act_c[0][0]);
        endfunction
    endclass

    // ======================================================================
    // 2a. Sequence: Python golden-model vectors
    // ======================================================================
    class matrix_vector_seq extends uvm_sequence #(matrix_item);
        `uvm_object_utils(matrix_vector_seq)

        `include "vectors.svh"      // VEC_N, NUM_VECTORS, vec_data[][]  (generated by golden_model.py)

        function new(string name = "matrix_vector_seq");
            super.new(name);
        endfunction

        task body();
            matrix_item item;
            if (VEC_N != N)
                `uvm_fatal("SEQ", $sformatf("vectors.svh was generated for N=%0d but the testbench is compiled for N=%0d", VEC_N, N))
            for (int v = 0; v < NUM_VECTORS; v++) begin
                item = matrix_item::type_id::create($sformatf("vec%0d", v));
                start_item(item);
                for (int i = 0; i < N; i++) begin
                    for (int j = 0; j < N; j++) begin
                        item.a[i][j]     = vec_data[v][i*N + j];
                        item.b[i][j]     = vec_data[v][N*N + i*N + j];
                        item.exp_c[i][j] = vec_data[v][2*N*N + i*N + j];
                    end
                end
                finish_item(item);
            end
            `uvm_info("SEQ", $sformatf("sent %0d Python golden-model vectors", NUM_VECTORS), UVM_LOW)
        endtask
    endclass

    // ======================================================================
    // 2b. Sequence: SystemVerilog constrained-random
    // ======================================================================
    class matrix_rand_seq extends uvm_sequence #(matrix_item);
        `uvm_object_utils(matrix_rand_seq)

        int unsigned count = 200;

        function new(string name = "matrix_rand_seq");
            super.new(name);
        endfunction

        task body();
            matrix_item item;
            for (int v = 0; v < count; v++) begin
                item = matrix_item::type_id::create($sformatf("rnd%0d", v));
                start_item(item);
                if (!item.randomize())
                    `uvm_fatal("SEQ", "randomize() failed")
                finish_item(item);
            end
            `uvm_info("SEQ", $sformatf("sent %0d constrained-random transactions", count), UVM_LOW)
        endtask
    endclass

    // ======================================================================
    // 3. Driver
    // ======================================================================
    class matrix_driver extends uvm_driver #(matrix_item);
        `uvm_component_utils(matrix_driver)

        vif_t vif;
        uvm_analysis_port #(matrix_item) exp_ap;     // "expected" side -> scoreboard

        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction

        function void build_phase(uvm_phase phase);
            super.build_phase(phase);
            exp_ap = new("exp_ap", this);
            if (!uvm_config_db#(vif_t)::get(this, "", "vif", vif))
                `uvm_fatal("DRV", "No vif found in config_db")
        endfunction

        task run_phase(uvm_phase phase);
            matrix_item item;
            vif.rst   <= 1'b1;
            vif.start <= 1'b0;
            repeat (3) @(posedge vif.clk);
            vif.rst   <= 1'b0;
            @(posedge vif.clk);

            forever begin
                seq_item_port.get_next_item(item);

                @(posedge vif.clk);                 // drive operands + a ONE-cycle start pulse
                vif.A     <= item.a;
                vif.B     <= item.b;
                vif.start <= 1'b1;
                exp_ap.write(item);

                @(posedge vif.clk);                 // DUT samples start on this edge
                vif.start <= 1'b0;

                do @(negedge vif.clk); while (vif.done !== 1'b1);   // wait for the result

                seq_item_port.item_done();
            end
        endtask
    endclass

    // ======================================================================
    // 4. Monitor -- passive: watches the pins only, one transaction per computation
    // ======================================================================
    class matrix_monitor extends uvm_monitor;
        `uvm_component_utils(matrix_monitor)

        vif_t vif;
        uvm_analysis_port #(matrix_item) ap;

        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction

        function void build_phase(uvm_phase phase);
            super.build_phase(phase);
            ap = new("ap", this);
            if (!uvm_config_db#(vif_t)::get(this, "", "vif", vif))
                `uvm_fatal("MON", "No vif found in config_db")
        endfunction

        task run_phase(uvm_phase phase);
            matrix_item item;
            forever begin
                @(posedge vif.clk);
                if (vif.rst !== 1'b1 && vif.start === 1'b1 && vif.busy !== 1'b1) begin
                    item   = matrix_item::type_id::create("mon_item");
                    item.a = vif.A;                  // operands exactly as the DUT sampled them
                    item.b = vif.B;
                    do @(negedge vif.clk); while (vif.done !== 1'b1);
                    item.act_c = vif.C;
                    ap.write(item);
                end
            end
        endtask
    endclass

    // ======================================================================
    // 5. Scoreboard
    // ======================================================================
    class matrix_scoreboard extends uvm_scoreboard;
        `uvm_component_utils(matrix_scoreboard)

        uvm_tlm_analysis_fifo #(matrix_item) exp_fifo;
        uvm_tlm_analysis_fifo #(matrix_item) act_fifo;
        int unsigned pass_cnt = 0;
        int unsigned fail_cnt = 0;
        int unsigned sync_cnt = 0;

        function new(string name, uvm_component parent);
            super.new(name, parent);
            exp_fifo = new("exp_fifo", this);
            act_fifo = new("act_fifo", this);
        endfunction

        task run_phase(uvm_phase phase);
            matrix_item e, a;
            bit ok, same_in;
            forever begin
                exp_fifo.get(e);
                act_fifo.get(a);

                same_in = 1'b1;                      // sanity: both streams are about the same A,B
                for (int i = 0; i < N; i++)
                    for (int j = 0; j < N; j++)
                        if (e.a[i][j] !== a.a[i][j] || e.b[i][j] !== a.b[i][j]) same_in = 1'b0;
                if (!same_in) begin
                    sync_cnt++;
                    `uvm_error("SB", "expected/actual streams out of step (operands differ)")
                end

                ok = 1'b1;
                for (int i = 0; i < N; i++) begin
                    for (int j = 0; j < N; j++) begin
                        if (e.exp_c[i][j] !== a.act_c[i][j]) begin
                            if (ok)
                                `uvm_error("SB", $sformatf("FAIL: C[%0d][%0d] expected %0d got %0d   (A[0][0]=%0d B[0][0]=%0d)",
                                           i, j, e.exp_c[i][j], a.act_c[i][j], e.a[0][0], e.b[0][0]))
                            ok = 1'b0;
                        end
                    end
                end
                if (ok) pass_cnt++; else fail_cnt++;
            end
        endtask

        function void report_phase(uvm_phase phase);
            `uvm_info("SB", $sformatf("TOTAL RESULT: %0d PASS, %0d FAIL (N=%0d)", pass_cnt, fail_cnt, N), UVM_LOW)
            if (fail_cnt == 0 && sync_cnt == 0 && pass_cnt > 0) `uvm_info("SB", "** SCOREBOARD: ALL CHECKS PASSED **", UVM_LOW)
            else                                                 `uvm_info("SB", "** SCOREBOARD: FAILURES PRESENT **", UVM_LOW)
        endfunction
    endclass

    // ======================================================================
    // 6. Functional coverage
    // ======================================================================
    class matrix_coverage extends uvm_subscriber #(matrix_item);
        `uvm_component_utils(matrix_coverage)

        mat_kind_e   a_kind, b_kind;
        int unsigned a_max, b_max;
        bit          c_zero;

        covergroup cg;
            option.per_instance = 1;
            cp_a_kind : coverpoint a_kind;
            cp_b_kind : coverpoint b_kind;
            cp_a_max  : coverpoint a_max { bins zero = {0};  bins low = {[1:15]};    bins mid = {[16:239]};
                                           bins big  = {[240:254]};                    bins full = {255}; }
            cp_b_max  : coverpoint b_max { bins zero = {0};  bins low = {[1:15]};    bins mid = {[16:239]};
                                           bins big  = {[240:254]};                    bins full = {255}; }
            cx_kinds  : cross cp_a_kind, cp_b_kind;
            cp_c_zero : coverpoint c_zero;
        endgroup

        function new(string name, uvm_component parent);
            super.new(name, parent);
            cg = new();
        endfunction

        function mat_kind_e classify(mat_t m);
            bit all_zero, is_ident, all_max;
            int zeros;
            all_zero = 1'b1; is_ident = 1'b1; all_max = 1'b1; zeros = 0;
            for (int i = 0; i < N; i++) begin
                for (int j = 0; j < N; j++) begin
                    if (m[i][j] != 0)               all_zero = 1'b0; else zeros++;
                    if (m[i][j] != ((i == j) ? 1 : 0)) is_ident = 1'b0;
                    if (m[i][j] != MAXV)            all_max  = 1'b0;
                end
            end
            if (all_zero) return K_ZERO;
            if (is_ident) return K_IDENT;
            if (all_max)  return K_ALLMAX;
            if (zeros > 0) return K_SPARSE;
            return K_DENSE;
        endfunction

        function int unsigned max_elem(mat_t m);
            int unsigned mx;
            mx = 0;
            for (int i = 0; i < N; i++)
                for (int j = 0; j < N; j++)
                    if (m[i][j] > mx) mx = m[i][j];
            return mx;
        endfunction

        function void write(matrix_item t);
            a_kind = classify(t.a);
            b_kind = classify(t.b);
            a_max  = max_elem(t.a);
            b_max  = max_elem(t.b);
            c_zero = 1'b1;
            for (int i = 0; i < N; i++)
                for (int j = 0; j < N; j++)
                    if (t.act_c[i][j] != 0) c_zero = 1'b0;
            cg.sample();
        endfunction

        function void report_phase(uvm_phase phase);
            `uvm_info("COV", $sformatf("FUNCTIONAL COVERAGE = %0.2f %%", cg.get_inst_coverage()), UVM_LOW)
        endfunction
    endclass

    // ======================================================================
    // 7. Agent / 8. Environment
    // ======================================================================
    class matrix_agent extends uvm_agent;
        `uvm_component_utils(matrix_agent)

        matrix_driver                    driver;
        matrix_monitor                   monitor;
        uvm_sequencer #(matrix_item)     sequencer;

        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction

        function void build_phase(uvm_phase phase);
            super.build_phase(phase);
            driver    = matrix_driver::type_id::create("driver", this);
            monitor   = matrix_monitor::type_id::create("monitor", this);
            sequencer = uvm_sequencer#(matrix_item)::type_id::create("sequencer", this);
        endfunction

        function void connect_phase(uvm_phase phase);
            super.connect_phase(phase);
            driver.seq_item_port.connect(sequencer.seq_item_export);
        endfunction
    endclass

    class matrix_env extends uvm_env;
        `uvm_component_utils(matrix_env)

        matrix_agent       agent;
        matrix_scoreboard  sb;
        matrix_coverage    cov;

        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction

        function void build_phase(uvm_phase phase);
            super.build_phase(phase);
            agent = matrix_agent::type_id::create("agent", this);
            sb    = matrix_scoreboard::type_id::create("sb", this);
            cov   = matrix_coverage::type_id::create("cov", this);
        endfunction

        function void connect_phase(uvm_phase phase);
            super.connect_phase(phase);
            agent.driver.exp_ap.connect(sb.exp_fifo.analysis_export);
            agent.monitor.ap.connect(sb.act_fifo.analysis_export);
            agent.monitor.ap.connect(cov.analysis_export);
        endfunction
    endclass

    // ======================================================================
    // 9. Tests
    // ======================================================================
    class matrix_test extends uvm_test;
        `uvm_component_utils(matrix_test)

        matrix_env env;

        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction

        function void build_phase(uvm_phase phase);
            super.build_phase(phase);
            env = matrix_env::type_id::create("env", this);
        endfunction

        virtual task run_sequences();
            matrix_vector_seq vseq;
            vseq = matrix_vector_seq::type_id::create("vseq");
            vseq.start(env.agent.sequencer);
        endtask

        task run_phase(uvm_phase phase);
            phase.raise_objection(this);
            run_sequences();
            #100;                                  // let the last result reach the scoreboard
            phase.drop_objection(this);
        endtask
    endclass

    class matrix_rand_test extends matrix_test;
        `uvm_component_utils(matrix_rand_test)
        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction
        virtual task run_sequences();
            matrix_rand_seq rseq;
            rseq = matrix_rand_seq::type_id::create("rseq");
            rseq.start(env.agent.sequencer);
        endtask
    endclass

    class matrix_full_test extends matrix_test;
        `uvm_component_utils(matrix_full_test)
        function new(string name, uvm_component parent);
            super.new(name, parent);
        endfunction
        virtual task run_sequences();
            matrix_vector_seq vseq;
            matrix_rand_seq   rseq;
            vseq = matrix_vector_seq::type_id::create("vseq");
            rseq = matrix_rand_seq::type_id::create("rseq");
            vseq.start(env.agent.sequencer);
            rseq.start(env.agent.sequencer);
        endtask
    endclass

endpackage
